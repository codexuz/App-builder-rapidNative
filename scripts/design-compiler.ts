import fs from 'node:fs';
import path from 'node:path';
import {
  AssetsManifestSchema,
  DesignTokensSchema,
  MotionSpecSchema,
  ScreensSpecSchema,
  type AssetsManifest,
  type DesignTokens,
  type MotionSpec,
  type ScreensSpec,
} from '../schemas';
import { getFactoryDir, recordStageStatus } from './lib/state';

interface CatalogComponent {
  id: string;
  category: string;
  source: string;
}

function readJsonIfExists(filePath: string): unknown | null {
  if (!fs.existsSync(filePath)) return null;
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function loadComponentCatalog(rootDir: string): Set<string> {
  const catalogPath = path.join(rootDir, 'knowledge', 'component-catalog.json');
  if (!fs.existsSync(catalogPath)) return new Set();
  const raw = JSON.parse(fs.readFileSync(catalogPath, 'utf8')) as {
    components?: CatalogComponent[];
  };
  return new Set((raw.components ?? []).map((c) => c.id));
}

function emitCompiledTokensTs(tokens: DesignTokens, motion: MotionSpec | null): string {
  const light = tokens.theme.light;
  const dark = tokens.theme.dark ?? tokens.theme.light;
  const u = tokens.theme.spacingUnit;
  const duration = motion?.duration ?? { instant: 100, fast: 180, normal: 300, slow: 480 };
  const springs = motion?.springs ?? {
    gentle: { damping: 20, stiffness: 140, mass: 1 },
    snappy: { damping: 18, stiffness: 280, mass: 0.8 },
    bouncy: { damping: 12, stiffness: 190, mass: 0.9 },
  };

  return `// Auto-generated by scripts/design-compiler.ts from .factory/TOKENS.json
// Do not edit directly — update .factory/TOKENS.json and re-run \`pnpm app:compile ${tokens.project.slug}\`.

export const CompiledTokens = {
  project: ${JSON.stringify(tokens.project, null, 2)},
  visualDirection: ${JSON.stringify(tokens.visualDirection, null, 2)},
  defaultMode: ${JSON.stringify(tokens.theme.defaultMode)},
  colors: {
    light: ${JSON.stringify(light, null, 4)},
    dark: ${JSON.stringify(dark, null, 4)},
  },
  typography: ${JSON.stringify(tokens.theme.typography, null, 2)},
  radius: {
    sm: ${tokens.theme.radius.sm},
    md: ${tokens.theme.radius.md},
    lg: ${tokens.theme.radius.lg},
    xl: ${tokens.theme.radius.xl},
    pill: 9999,
  },
  spacing: {
    xs: ${u},
    sm: ${u * 2},
    md: ${u * 3},
    lg: ${u * 4},
    xl: ${u * 6},
    xxl: ${u * 8},
    xxxl: ${u * 12},
  },
  motion: {
    respectReducedMotion: ${motion?.respectReducedMotion ?? true},
    hapticsEnabled: ${motion?.hapticsEnabled ?? true},
    duration: ${JSON.stringify(duration, null, 4)},
    springs: ${JSON.stringify(springs, null, 4)},
  },
} as const;
`;
}

function emitImplementationBrief(
  tokens: DesignTokens | null,
  screens: ScreensSpec | null,
  motion: MotionSpec | null,
  assets: AssetsManifest | null,
  warnings: string[]
): string {
  const lines: string[] = [
    '# Compiled Implementation Brief',
    '',
    `_Generated automatically by \`scripts/design-compiler.ts\` at ${new Date().toISOString()}_`,
    '',
  ];

  if (tokens) {
    lines.push(
      '## 1. Visual Direction & Tokens',
      `- **App:** ${tokens.project.name} (\`${tokens.project.slug}\`) — ${tokens.project.category}`,
      `- **Audience:** ${tokens.project.audience}`,
      `- **Direction:** \`${tokens.visualDirection.primary}\`${tokens.visualDirection.secondary ? ` + \`${tokens.visualDirection.secondary}\`` : ''} (mode: \`${tokens.visualDirection.surfaceMode}\`)`,
      `- **Rationale:** ${tokens.visualDirection.rationale}`,
      `- **Default Theme:** \`${tokens.theme.defaultMode}\` · Accent \`${tokens.theme.light.accent}\` · Ground \`${tokens.theme.light.background}\``,
      `- **Compiled Tokens:** \`constants/CompiledTokens.ts\``,
      ''
    );
    if (tokens.visualDirection.antiPatternsToAvoid.length > 0) {
      lines.push('**Anti-Patterns to Avoid:**');
      for (const ap of tokens.visualDirection.antiPatternsToAvoid) {
        lines.push(`- ${ap}`);
      }
      lines.push('');
    }
  }

  if (screens) {
    lines.push(
      '## 2. Navigation & Screen Specifications',
      `- **Navigation Pattern:** \`${screens.navigation.type}\``,
      ''
    );
    for (const s of screens.screens) {
      lines.push(
        `### ${s.title} (\`${s.route}\`)`,
        `- **Purpose:** ${s.purpose}`,
        `- **Layout:** \`${s.layout}\``,
        `- **Components:** ${s.components.map((c) => `\`${c}\``).join(', ')}`,
        `- **Assets:** ${s.assets.length > 0 ? s.assets.map((a) => `\`${a}\``).join(', ') : 'None'}`,
        `- **States:** loading=${s.states.loading} | empty=${s.states.empty} | error=${s.states.error}`,
        ''
      );
    }
  }

  if (motion) {
    lines.push(
      '## 3. Motion Specification',
      `- **Engine:** \`${motion.engine}\` · Haptics: \`${motion.hapticsEnabled}\` · Reduced Motion: \`${motion.respectReducedMotion}\``,
      ''
    );
    for (const item of motion.interactions) {
      lines.push(`- **${item.target}** (${item.trigger}): ${item.behavior}`);
    }
    lines.push('');
  }

  if (assets) {
    lines.push(
      '## 4. Asset Manifest',
      `- **Model:** \`${assets.defaultModel ?? 'default'}\``,
      `- **Total Assets:** ${assets.assets.length}`,
      ''
    );
    for (const a of assets.assets) {
      lines.push(`- \`${a.key}\` (${a.type}, ${a.aspectRatio}) -> \`assets/generated/${a.filename}\` [${a.status}]`);
    }
    lines.push('');
  }

  if (warnings.length > 0) {
    lines.push('## Validation Notes');
    for (const w of warnings) {
      lines.push(`- ${w}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

function main(): void {
  const slug = process.argv[2];
  if (!slug) {
    console.error('Usage: pnpm app:compile <app-slug>');
    process.exit(1);
  }

  const rootDir = process.cwd();
  const appDir = path.join(rootDir, 'apps', slug);
  if (!fs.existsSync(appDir)) {
    console.error(`App not found: ${appDir}`);
    process.exit(1);
  }

  const factoryDir = getFactoryDir(appDir);
  fs.mkdirSync(factoryDir, { recursive: true });
  recordStageStatus(appDir, slug, 'compile', 'running');

  const warnings: string[] = [];
  const errors: string[] = [];

  // 1. Validate TOKENS.json
  let tokens: DesignTokens | null = null;
  const rawTokens = readJsonIfExists(path.join(factoryDir, 'TOKENS.json'));
  if (rawTokens) {
    const parsed = DesignTokensSchema.safeParse(rawTokens);
    if (!parsed.success) {
      errors.push(`TOKENS.json validation failed:\n${parsed.error.toString()}`);
    } else {
      tokens = parsed.data;
    }
  } else {
    warnings.push('No .factory/TOKENS.json found — skipped constants/CompiledTokens.ts generation.');
  }

  // 2. Validate SCREENS.json
  let screens: ScreensSpec | null = null;
  const rawScreens = readJsonIfExists(path.join(factoryDir, 'SCREENS.json'));
  if (rawScreens) {
    const parsed = ScreensSpecSchema.safeParse(rawScreens);
    if (!parsed.success) {
      errors.push(`SCREENS.json validation failed:\n${parsed.error.toString()}`);
    } else {
      screens = parsed.data;
    }
  } else {
    warnings.push('No .factory/SCREENS.json found.');
  }

  // 3. Validate MOTION.json
  let motion: MotionSpec | null = null;
  const rawMotion = readJsonIfExists(path.join(factoryDir, 'MOTION.json'));
  if (rawMotion) {
    const parsed = MotionSpecSchema.safeParse(rawMotion);
    if (!parsed.success) {
      errors.push(`MOTION.json validation failed:\n${parsed.error.toString()}`);
    } else {
      motion = parsed.data;
    }
  }

  // 4. Validate ASSETS.json (or fallback to assets.manifest.json)
  let assets: AssetsManifest | null = null;
  const assetsFile = fs.existsSync(path.join(factoryDir, 'ASSETS.json'))
    ? path.join(factoryDir, 'ASSETS.json')
    : path.join(appDir, 'assets.manifest.json');
  const rawAssets = readJsonIfExists(assetsFile);
  if (rawAssets) {
    const parsed = AssetsManifestSchema.safeParse(rawAssets);
    if (!parsed.success) {
      errors.push(`${path.basename(assetsFile)} validation failed:\n${parsed.error.toString()}`);
    } else {
      assets = parsed.data;
    }
  }

  // 5. Cross-reference checks (components vs catalog, screen assets vs manifest)
  const catalogIds = loadComponentCatalog(rootDir);
  if (screens && catalogIds.size > 0) {
    const customComponents = new Set<string>();
    for (const screen of screens.screens) {
      for (const comp of screen.components) {
        if (!catalogIds.has(comp)) {
          customComponents.add(comp);
        }
      }
    }
    if (customComponents.size > 0) {
      warnings.push(
        `App-specific custom components to implement: ${Array.from(customComponents).join(', ')}`
      );
    }
  }

  if (screens && assets) {
    const declaredAssetKeys = new Set(assets.assets.map((a) => a.key));
    for (const screen of screens.screens) {
      for (const assetKey of screen.assets) {
        if (!declaredAssetKeys.has(assetKey)) {
          errors.push(
            `Screen "${screen.id}" references asset "${assetKey}", which is missing from ${path.basename(assetsFile)}.`
          );
        }
      }
    }
  }

  if (errors.length > 0) {
    recordStageStatus(appDir, slug, 'compile', 'failed', { error: errors.join('\n') });
    console.error('Design Compiler failed:\n');
    for (const e of errors) console.error(`  ✗ ${e}`);
    process.exit(1);
  }

  // 6. Emit compiled outputs
  if (tokens) {
    const compiledPath = path.join(appDir, 'constants', 'CompiledTokens.ts');
    fs.mkdirSync(path.dirname(compiledPath), { recursive: true });
    fs.writeFileSync(compiledPath, emitCompiledTokensTs(tokens, motion), 'utf8');
    console.log(`✓ Generated ${path.relative(rootDir, compiledPath)}`);
  }

  const briefPath = path.join(factoryDir, 'IMPLEMENTATION_BRIEF.md');
  fs.writeFileSync(
    briefPath,
    emitImplementationBrief(tokens, screens, motion, assets, warnings),
    'utf8'
  );
  console.log(`✓ Generated ${path.relative(rootDir, briefPath)}`);

  for (const w of warnings) {
    console.log(`  ℹ ${w}`);
  }

  recordStageStatus(appDir, slug, 'compile', 'passed', {
    artifactPath: path.relative(rootDir, briefPath),
  });
  console.log(`\nDesign compilation passed for "${slug}".`);
}

main();
